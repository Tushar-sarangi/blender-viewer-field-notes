"""Build two public-safe scenes that exercise evaluated browser playback.

Run from Blender 5.x with:
  blender --background --python examples/build_evaluated_demos.py -- --output-dir PATH
Then export each saved .blend with blender-viewer-bake.py.
"""

from __future__ import annotations

import argparse
import math
import os
import sys

import bpy
from mathutils import Vector


def arguments() -> argparse.Namespace:
    argv = sys.argv[sys.argv.index("--") + 1 :] if "--" in sys.argv else []
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", required=True)
    return parser.parse_args(argv)


def material(name: str, color: tuple[float, float, float], metallic: float = 0.0, roughness: float = 0.45) -> bpy.types.Material:
    mat = bpy.data.materials.new(name)
    mat.diffuse_color = (*color, 1.0)
    mat.use_nodes = True
    shader = mat.node_tree.nodes.get("Principled BSDF")
    shader.inputs["Base Color"].default_value = (*color, 1.0)
    shader.inputs["Metallic"].default_value = metallic
    shader.inputs["Roughness"].default_value = roughness
    return mat


def empty_scene() -> bpy.types.Scene:
    bpy.ops.wm.read_factory_settings(use_empty=True)
    scene = bpy.context.scene
    scene.frame_start = 1
    scene.frame_end = 73
    scene["Example credit"] = "Generated by OpenAI Codex (OC), 2026"
    scene.render.fps = 24
    scene.render.engine = "BLENDER_EEVEE"
    scene.render.resolution_x = 800
    scene.render.resolution_y = 450
    scene.render.resolution_percentage = 60
    scene.render.image_settings.file_format = "PNG"
    scene.render.film_transparent = False
    scene.view_settings.view_transform = "AgX"
    if scene.world:
        scene.world.color = (0.025, 0.035, 0.055)
    return scene


def aim(obj: bpy.types.Object, target: tuple[float, float, float]) -> None:
    direction = Vector(target) - obj.location
    obj.rotation_euler = direction.to_track_quat("-Z", "Y").to_euler()


def stage(scene: bpy.types.Scene, target: tuple[float, float, float], camera_position: tuple[float, float, float], poster_path: str) -> None:
    bpy.ops.object.camera_add(location=camera_position)
    camera = bpy.context.object
    camera.name = "Showcase Camera"
    aim(camera, target)
    camera.data.lens = 48
    scene.camera = camera

    for name, location, energy, size in (
        ("Key", (4.0, -5.0, 7.0), 1150, 6.0),
        ("Fill", (-4.0, 2.0, 4.5), 850, 5.0),
        ("Rim", (1.0, 5.0, 6.5), 1000, 4.0),
    ):
        bpy.ops.object.light_add(type="AREA", location=location)
        light = bpy.context.object
        light.name = name
        light.data.energy = energy
        light.data.shape = "DISK"
        light.data.size = size
        aim(light, target)

    scene.render.filepath = poster_path
    scene.frame_set(1)
    bpy.context.view_layer.update()
    bpy.ops.render.render(write_still=True)


def set_floor(size: float, color: tuple[float, float, float]) -> bpy.types.Object:
    bpy.ops.mesh.primitive_plane_add(size=size, location=(0, 0, 0))
    obj = bpy.context.object
    obj.name = "Stage Floor"
    obj.data.materials.append(material("Midnight slate", color, 0.12, 0.7))
    return obj


def make_constraint_arc(out_dir: str) -> None:
    scene = empty_scene()
    gold = material("Orbit brass", (0.92, 0.39, 0.08), 0.72, 0.24)
    cyan = material("Signal enamel", (0.045, 0.62, 0.78), 0.38, 0.25)
    dark = material("Stage indigo", (0.035, 0.055, 0.095), 0.22, 0.55)
    set_floor(10, (0.022, 0.032, 0.055))

    bpy.ops.mesh.primitive_cylinder_add(vertices=48, radius=0.52, depth=0.5, location=(0, 0, 0.25))
    pedestal = bpy.context.object
    pedestal.name = "Relay Pedestal"
    pedestal.data.materials.append(dark)
    bevel = pedestal.modifiers.new("Soft machined edge", "BEVEL")
    bevel.width = 0.08
    bevel.segments = 3
    pedestal.modifiers.new("Weighted corner normals", "WEIGHTED_NORMAL")

    bpy.ops.mesh.primitive_torus_add(major_radius=2.35, minor_radius=0.035, major_segments=96, minor_segments=8, location=(0, 0, 1.45))
    torus = bpy.context.object
    torus.name = "Visible Orbit Ring"
    torus.data.materials.append(gold)

    curve = bpy.data.curves.new("Constraint Orbit Path", "CURVE")
    curve.dimensions = "3D"
    curve.resolution_u = 24
    curve.path_duration = 72
    curve.use_path = True
    curve.bevel_depth = 0.018
    curve.bevel_resolution = 2
    spline = curve.splines.new("POLY")
    spline.points.add(63)
    for index, point in enumerate(spline.points):
        angle = math.tau * index / 64
        point.co = (2.35 * math.cos(angle), 2.35 * math.sin(angle), 1.45, 1.0)
    spline.use_cyclic_u = True
    path = bpy.data.objects.new("Constraint Orbit Path", curve)
    scene.collection.objects.link(path)
    curve.materials.append(gold)
    curve.eval_time = 0
    curve.keyframe_insert(data_path="eval_time", frame=1)
    curve.eval_time = 72
    curve.keyframe_insert(data_path="eval_time", frame=73)

    bpy.ops.mesh.primitive_uv_sphere_add(segments=24, ring_count=12, radius=0.32, location=(0, 0, 0))
    satellite = bpy.context.object
    satellite.name = "Path-bound Signal"
    satellite.data.materials.append(cyan)
    satellite_subsurf = satellite.modifiers.new("Polished silhouette", "SUBSURF")
    satellite_subsurf.levels = 1
    follow = satellite.constraints.new("FOLLOW_PATH")
    follow.name = "Follow the orbit curve"
    follow.target = path
    follow.use_curve_follow = True
    follow.forward_axis = "FORWARD_X"
    follow.up_axis = "UP_Z"

    bpy.ops.mesh.primitive_uv_sphere_add(segments=12, ring_count=8, radius=0.11, location=(0, 0, 0))
    beacon = bpy.context.object
    beacon.name = "Constraint-linked Beacon"
    beacon.data.materials.append(gold)
    copy = beacon.constraints.new("COPY_LOCATION")
    copy.name = "Stay with signal"
    copy.target = satellite
    copy.use_offset = True
    beacon.location.z = 0.55

    # Three display pylons make the orbit easy to read while the path itself
    # remains visible and still drives the Follow Path constraint.
    for index, angle in enumerate((0.25, 2.35, 4.45), start=1):
        x, y = 2.35 * math.cos(angle), 2.35 * math.sin(angle)
        bpy.ops.mesh.primitive_cylinder_add(vertices=20, radius=0.075, depth=1.1, location=(x, y, 0.55))
        post = bpy.context.object
        post.name = f"Orbit marker {index}"
        post.data.materials.append(gold)

    scene.frame_current = 1
    stage(scene, (0, 0, 0.9), (7.6, -9.2, 6.4), os.path.join(out_dir, "constraint-arc-poster.png"))
    bpy.ops.wm.save_as_mainfile(filepath=os.path.join(out_dir, "constraint-arc.blend"))


def make_rigged_mesh() -> bpy.types.Object:
    vertices = [
        (-0.12, -0.08, 2.05), (-1.25, -0.05, 2.35), (-1.08, 0.48, 2.05), (-0.15, 0.25, 1.95),
        (0.12, -0.08, 2.05), (1.25, -0.05, 2.35), (1.08, 0.48, 2.05), (0.15, 0.25, 1.95),
        (-0.13, -0.13, 2.1), (0.13, -0.13, 2.1), (0.0, -0.36, 2.0), (0.0, 0.2, 2.0),
    ]
    faces = [(0, 1, 2, 3), (4, 7, 6, 5), (8, 9, 10), (8, 11, 9)]
    mesh = bpy.data.meshes.new("Skinned paper sail")
    mesh.from_pydata(vertices, [], faces)
    mesh.update()
    obj = bpy.data.objects.new("NLA-flapping Sail", mesh)
    bpy.context.scene.collection.objects.link(obj)
    obj.data.materials.append(material("Sail teal", (0.025, 0.55, 0.72), 0.2, 0.3))
    obj.data.materials.append(material("Sail amber", (0.98, 0.46, 0.12), 0.12, 0.34))
    for polygon in mesh.polygons:
        polygon.material_index = 1 if polygon.index >= 2 else 0
    return obj


def make_rig_and_nla(obj: bpy.types.Object) -> None:
    armature = bpy.data.armatures.new("Sail bones")
    rig = bpy.data.objects.new("NLA Sail Rig", armature)
    bpy.context.scene.collection.objects.link(rig)
    bpy.context.view_layer.objects.active = rig
    rig.select_set(True)
    bpy.ops.object.mode_set(mode="EDIT")
    body = armature.edit_bones.new("Body")
    body.head = (0, 0, 1.65)
    body.tail = (0, 0, 2.05)
    left = armature.edit_bones.new("Wing.L")
    left.head = (0, 0, 2.05)
    left.tail = (-1.05, 0, 2.05)
    left.parent = body
    right = armature.edit_bones.new("Wing.R")
    right.head = (0, 0, 2.05)
    right.tail = (1.05, 0, 2.05)
    right.parent = body
    bpy.ops.object.mode_set(mode="OBJECT")
    rig.select_set(False)

    group_body = obj.vertex_groups.new(name="Body")
    group_left = obj.vertex_groups.new(name="Wing.L")
    group_right = obj.vertex_groups.new(name="Wing.R")
    for index, vertex in enumerate(obj.data.vertices):
        x = vertex.co.x
        if abs(x) < 0.14:
            group_body.add([index], 1.0, "REPLACE")
        elif x < 0:
            group_left.add([index], 1.0, "REPLACE")
        else:
            group_right.add([index], 1.0, "REPLACE")
    modifier = obj.modifiers.new("Armature deformation", "ARMATURE")
    modifier.object = rig

    rig.animation_data_create()
    for bone_name, sign in (("Wing.L", -1), ("Wing.R", 1)):
        pose = rig.pose.bones[bone_name]
        pose.rotation_mode = "XYZ"
        for frame, angle in ((1, 0.0), (7, sign * 0.78), (13, 0.0), (19, -sign * 0.68), (25, 0.0)):
            pose.rotation_euler[0] = angle
            pose.keyframe_insert(data_path="rotation_euler", frame=frame, group=bone_name)
    action = rig.animation_data.action
    action.name = "Alternating sail flap"
    track = rig.animation_data.nla_tracks.new()
    track.name = "Looping pose study"
    strip = track.strips.new("Three NLA cycles", 1, action)
    strip.repeat = 3
    rig.animation_data.action = None


def make_physics_dominoes() -> None:
    floor = bpy.context.scene.objects.get("Stage Floor")
    if floor is None:
        floor = set_floor(12, (0.025, 0.04, 0.065))
    bpy.context.view_layer.objects.active = floor
    floor.select_set(True)
    bpy.ops.rigidbody.object_add(type="PASSIVE")
    floor.rigid_body.friction = 0.72
    floor.select_set(False)

    active = []
    palette = [
        material("Impact coral", (0.92, 0.12, 0.11), 0.08, 0.34),
        material("Impact apricot", (1.0, 0.42, 0.13), 0.1, 0.33),
        material("Impact lemon", (0.94, 0.72, 0.12), 0.08, 0.36),
    ]
    for index in range(6):
        x = 1.15 + index * 0.42
        bpy.ops.mesh.primitive_cube_add(size=1, location=(x, 0, 0.5))
        domino = bpy.context.object
        domino.name = f"Physics domino {index + 1}"
        domino.dimensions = (0.16, 0.58, 1.0)
        bpy.ops.object.transform_apply(location=False, rotation=False, scale=True)
        domino.data.materials.append(palette[index % len(palette)])
        if index == 0:
            # A slight forward lean lets gravity start the domino chain.
            domino.rotation_euler[1] = 0.22
        bevel = domino.modifiers.new("Rounded domino corners", "BEVEL")
        bevel.width = 0.055
        bevel.segments = 3
        bpy.context.view_layer.objects.active = domino
        bpy.ops.rigidbody.object_add(type="ACTIVE")
        domino.rigid_body.mass = 0.28
        domino.rigid_body.friction = 0.55
        domino.rigid_body.restitution = 0.16
        active.append(domino)

    bpy.ops.mesh.primitive_uv_sphere_add(segments=24, ring_count=12, radius=0.36, location=(0.8, 0, 1.5))
    marble = bpy.context.object
    marble.name = "Physics marble"
    marble.data.materials.append(material("Marble cobalt", (0.035, 0.25, 0.9), 0.48, 0.2))
    bpy.context.view_layer.objects.active = marble
    bpy.ops.rigidbody.object_add(type="ACTIVE")
    marble.rigid_body.mass = 1.1
    marble.rigid_body.friction = 0.28
    marble.rigid_body.restitution = 0.32
    active.append(marble)

    if bpy.context.scene.rigidbody_world is None:
        bpy.ops.rigidbody.world_add()
    world = bpy.context.scene.rigidbody_world
    world.substeps_per_frame = 12
    world.solver_iterations = 20
    for obj in active:
        obj.select_set(True)
    bpy.context.view_layer.objects.active = marble
    # Bake the Bullet cache before saving so the evaluated browser export
    # samples real rigid-body motion instead of static starting transforms.
    scene = bpy.context.scene
    world.point_cache.frame_start = scene.frame_start
    world.point_cache.frame_end = scene.frame_end
    scene.frame_set(scene.frame_start)
    result = bpy.ops.ptcache.bake_all(bake=True)
    if "FINISHED" not in result or not world.point_cache.is_baked:
        raise RuntimeError(f"Could not bake rigid-body cache: {result}")
    scene.frame_set(scene.frame_start)


def make_animated_modifier() -> None:
    bpy.ops.mesh.primitive_cylinder_add(vertices=32, radius=0.32, depth=1.8, location=(-2.15, 0, 0.95))
    column = bpy.context.object
    column.name = "Animated modifier column"
    column.data.materials.append(material("Flex violet", (0.36, 0.22, 0.82), 0.42, 0.25))
    for polygon in column.data.polygons:
        polygon.use_smooth = True
    sub = column.modifiers.new("Subdivision surface", "SUBSURF")
    sub.levels = 2
    deform = column.modifiers.new("Animated twist modifier", "SIMPLE_DEFORM")
    deform.deform_method = "TWIST"
    deform.deform_axis = "Z"
    for frame, angle in ((1, -0.3), (19, 0.85), (37, 1.3), (55, 0.25), (73, -0.3)):
        deform.angle = angle
        column.keyframe_insert(data_path='modifiers["Animated twist modifier"].angle', frame=frame)


def make_rig_physics_modifier(out_dir: str) -> None:
    scene = empty_scene()
    set_floor(12, (0.025, 0.04, 0.065))
    sail = make_rigged_mesh()
    make_rig_and_nla(sail)
    make_animated_modifier()
    make_physics_dominoes()
    scene.frame_set(1)
    stage(scene, (0.2, 0, 1.15), (7.5, -11.5, 7.2), os.path.join(out_dir, "motion-mechanics-poster.png"))
    bpy.ops.wm.save_as_mainfile(filepath=os.path.join(out_dir, "motion-mechanics.blend"))


def main() -> None:
    out_dir = os.path.abspath(arguments().output_dir)
    os.makedirs(out_dir, exist_ok=True)
    make_constraint_arc(out_dir)
    make_rig_physics_modifier(out_dir)
    print(f"Generated Blender viewer demos in {out_dir}")


if __name__ == "__main__":
    main()
